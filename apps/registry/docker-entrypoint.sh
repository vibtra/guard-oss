set -eu
umask 077

fail() {
  echo "[guard] $1" >&2
  exit 1
}

case "${REGISTRY_BASE_URL:-}" in
  "") fail "Set REGISTRY_BASE_URL to the https:// address people and laptops use to reach this server." ;;
  https://*) ;;
  http://localhost | http://localhost:* | http://127.0.0.1 | http://127.0.0.1:* | "http://[::1]" | "http://[::1]:"*)
    echo "[guard] REGISTRY_BASE_URL is plain http on loopback. Use this for a local trial only." >&2 ;;
  *) fail "REGISTRY_BASE_URL must start with https:// (got ${REGISTRY_BASE_URL}). Put a TLS reverse proxy in front of Guard. Plain http is accepted only for localhost." ;;
esac

DATA="${VIBTRA_REGISTRY_DATA_DIR:-/data}"
SECRETS="$DATA/secrets.env"
[ -d "$DATA" ] && [ -w "$DATA" ] || fail "$DATA is not a writable directory. Mount the guard-data volume there."

if [ -n "${REGISTRY_SESSION_SECRET:-}" ] && [ -n "${REGISTRY_GATE_SIGNING_SECRET:-}" ] && [ -n "${VIBTRA_VAULT_KEY:-}" ]; then
  :
elif [ ! -f "$SECRETS" ]; then
  node -e '
    const pg = require("pg");
    const client = new pg.Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10000 });
    client.connect()
      .then(() => client.query("select to_regclass($1) as t", ["public.registry_migrations"]))
      .then(async (r) => (r.rows[0].t === null ? 0 : Number((await client.query("select count(*)::int as n from registry_migrations")).rows[0].n)))
      .then((n) => client.end().then(() => process.exit(n > 0 ? 3 : 0)))
      .catch((e) => { console.error("[guard] cannot reach the database: " + e.message); process.exit(4); });
  ' || case $? in
    3) fail "The database already holds Guard data, but $SECRETS is missing. Restore secrets.env from the backup taken with this database (docs/self-host.md). If you set REGISTRY_SESSION_SECRET, REGISTRY_GATE_SIGNING_SECRET and VIBTRA_VAULT_KEY yourself, put them back in the env file instead. To start over, use an empty database." ;;
    *) fail "Could not check the database before generating secrets. Check DATABASE_URL and that Postgres is running." ;;
  esac
  node -e '
    const { randomBytes } = require("node:crypto");
    const hex = () => randomBytes(32).toString("hex");
    process.stdout.write(
      `# Generated by Guard on first boot, ${new Date().toISOString()}. Back up with the database.\n` +
      `REGISTRY_SESSION_SECRET=${hex()}\nREGISTRY_GATE_SIGNING_SECRET=${hex()}\nVIBTRA_VAULT_KEY=${hex()}\n`,
    );
  ' > "$SECRETS.tmp"
  mv "$SECRETS.tmp" "$SECRETS"
  echo "[guard] generated server secrets in $SECRETS (first boot)" >&2
fi
[ ! -f "$SECRETS" ] || chmod 600 "$SECRETS"

for name in REGISTRY_SESSION_SECRET REGISTRY_GATE_SIGNING_SECRET VIBTRA_VAULT_KEY; do
  current=$(printenv "$name" || true)
  if [ -z "$current" ]; then
    value=$(sed -n "s/^$name=//p" "$SECRETS" | head -n 1)
    [ -n "$value" ] || fail "$SECRETS has no $name. Restore it from your backup; do not generate a new vault key for an existing database."
    export "$name=$value"
  fi
done

exec "$@"
